CREATE TABLE IF NOT EXISTS auth_email_challenges (
    token_hash CHAR(64) PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    code_hash CHAR(64) NOT NULL,
    attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_email_challenges_email ON auth_email_challenges (email);
CREATE INDEX IF NOT EXISTS auth_email_challenges_expiry ON auth_email_challenges (expires_at);
CREATE TABLE IF NOT EXISTS auth_oauth_states (
    state_hash CHAR(64) PRIMARY KEY,
    provider VARCHAR(10) NOT NULL CHECK (provider IN ('google','github')),
    verifier VARCHAR(128) NOT NULL,
    nonce CHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_oauth_states_expiry ON auth_oauth_states (expires_at);
CREATE TABLE IF NOT EXISTS auth_identities (
    provider VARCHAR(10) NOT NULL CHECK (provider IN ('google','github')),
    subject VARCHAR(255) NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    PRIMARY KEY (provider,subject),
    UNIQUE (usuario_id,provider)
);
