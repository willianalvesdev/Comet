CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    idade SMALLINT CHECK (idade BETWEEN 1 AND 120),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS usuarios_email_unique ON usuarios (lower(email));
CREATE TABLE IF NOT EXISTS sessoes (
    token_hash CHAR(64) PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    expira_em TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS sessoes_expiracao ON sessoes (expira_em);
CREATE TABLE IF NOT EXISTS computer_conversas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    titulo VARCHAR(100) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    requisicao_ativa UUID,
    ativa_ate TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS computer_conversas_usuario ON computer_conversas (usuario_id, atualizado_em, id);
CREATE TABLE IF NOT EXISTS computer_mensagens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversa_id BIGINT NOT NULL REFERENCES computer_conversas(id) ON DELETE CASCADE,
    requisicao_id UUID NOT NULL UNIQUE,
    pergunta TEXT NOT NULL,
    resposta TEXT NOT NULL,
    pensamento TEXT NOT NULL,
    estado VARCHAR(12) NOT NULL CHECK (estado IN ('running','completed','interrupted','failed')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS computer_mensagens_conversa ON computer_mensagens (conversa_id, id);
CREATE TABLE IF NOT EXISTS computer_personalizacao (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
    nome_preferido VARCHAR(100) NOT NULL DEFAULT '',
    ocupacao VARCHAR(200) NOT NULL DEFAULT '',
    sobre TEXT NOT NULL DEFAULT '',
    memoria_ativa BOOLEAN NOT NULL DEFAULT TRUE,
    resumo TEXT NOT NULL DEFAULT '',
    versao BIGINT NOT NULL DEFAULT 0,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS finance_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    external_id VARCHAR(100) NOT NULL,
    kind VARCHAR(7) NOT NULL CHECK (kind IN ('income','expense')),
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    description VARCHAR(200) NOT NULL,
    category VARCHAR(80) NOT NULL DEFAULT '',
    occurred_on DATE NOT NULL,
    occurred_time TIME,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ,
    UNIQUE (usuario_id, external_id)
);
CREATE INDEX IF NOT EXISTS finance_history ON finance_transactions (usuario_id, occurred_on, id);
CREATE TABLE IF NOT EXISTS finance_operations (
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    operation_id UUID NOT NULL,
    request_hash CHAR(64) NOT NULL,
    result JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (usuario_id, operation_id)
);
CREATE TABLE IF NOT EXISTS finance_transaction_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    operation_id UUID,
    transaction_id BIGINT NOT NULL,
    event VARCHAR(40) NOT NULL CHECK (event IN ('TRANSACTION_CREATED','TRANSACTION_UPDATED','TRANSACTION_DELETED','TRANSACTION_RESTORED','TRANSACTION_PERMANENTLY_DELETED')),
    occurred_at TIMESTAMPTZ NOT NULL,
    before_json JSONB,
    after_json JSONB
);
CREATE INDEX IF NOT EXISTS finance_event_history ON finance_transaction_events (usuario_id, transaction_id, id);
CREATE TABLE IF NOT EXISTS request_rate_limits (
    key CHAR(64) PRIMARY KEY,
    count INTEGER NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS request_rate_limits_expiration ON request_rate_limits (expires_at);


